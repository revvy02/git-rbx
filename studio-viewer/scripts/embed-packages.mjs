// Turn the rojo-built roblox_packages rbxm into a Luau module returning the
// bytes as base64, so the bundle carries its own packages and boots them
// through SerializationService instead of running rojo at launch.
//
//   node scripts/embed-packages.mjs build/packages.rbxm shared/generated/packages_blob.luau
import { readFileSync, writeFileSync } from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
	console.error("usage: embed-packages.mjs <packages.rbxm> <out.luau>");
	process.exit(2);
}
const bytes = readFileSync(input);
const b64 = bytes.toString("base64");
// 76-column lines keep the file diffable and well under Luau's string limits.
const lines = b64.match(/.{1,76}/g) ?? [];
const luau = [
	"-- @generated by scripts/embed-packages.mjs; do not edit.",
	`-- ${bytes.length} bytes of roblox_packages as an rbxm, base64.`,
	"return table.concat({",
	...lines.map((line) => `\t"${line}",`),
	"})",
	"",
].join("\n");
writeFileSync(output, luau);
console.log(`embedded ${bytes.length} bytes -> ${output}`);
